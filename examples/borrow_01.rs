// 借用与引用（一）：不可变引用 &T
//
// 上一节学了所有权：值传进函数后，原变量就不能用了（move）。
// 但很多时候我们只想"看一眼"数据，不想拿走所有权。
// 这就是"借用"——用 & 创建一个引用。

fn main() {
    let s = String::from("hello");

    // &s 创建一个指向 s 的引用，不会转移所有权
    let len = calc_len(&s);

    // s 还能用！因为我们只是"借"给了函数，没有"送"出去
    println!("\"{}\" 的长度是 {}", s, len);

    // 可以同时创建多个不可变引用，没问题
    let r1 = &s;
    let r2 = &s;
    println!("r1={}, r2={}", r1, r2);
}

// 参数类型是 &String —— 借用一个 String，不拿走所有权
// 类比：Go 里所有东西默认就是引用/指针传递
//       Java 里对象参数本质也是传引用
//       Rust 需要你显式写 & 来表达这个意图
fn calc_len(s: &String) -> usize {
    s.len()
    // 函数结束，s（引用）被丢弃，但原始数据不受影响
}
